// DataLab — build supabase/seed.sql from the game's catalog export (see export-catalog.js).
// usage: node supabase/scripts/build-seed.mjs catalog-export.json > supabase/seed.sql
import { readFileSync } from 'node:fs';

const X = JSON.parse(readFileSync(process.argv[2] || 'catalog-export.json', 'utf8'));
const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : typeof v === 'boolean' ? String(v) : "'" + String(v).replace(/'/g, "''") + "'");
const j = (v) => (v === null || v === undefined ? 'null' : q(JSON.stringify(v)) + '::jsonb');
const out = [];
const p = (s) => out.push(s);

p('-- DataLab · seed (generated by supabase/scripts/build-seed.mjs from the game catalog — do not edit by hand)');
p('-- Safe to run again: every insert updates the existing row.');
p('begin;');

// rarities, currencies, categories
p('\n-- rarities');
for (const [id, r] of Object.entries(X.rarity)) p(`insert into public.rarities (id, name, rank, color) values (${q(id)}, ${q(r.name)}, ${r.rank}, ${q(r.color)}) on conflict (id) do update set name = excluded.name, rank = excluded.rank, color = excluded.color;`);
p('\n-- currencies');
for (const [id, name, scope, premium] of [['cash', 'Dinheiro da empresa', 'company', false], ['credits', 'Créditos', 'player', false], ['gold', 'Gold (moeda dourada)', 'player', true]])
  p(`insert into public.currencies (id, name, scope, premium) values (${q(id)}, ${q(name)}, ${q(scope)}, ${premium}) on conflict (id) do update set name = excluded.name, scope = excluded.scope, premium = excluded.premium;`);
p('\n-- shop categories');
const cats = [['infra', 'Infraestrutura', 1], ['char', 'Personagem', 2], ['legend', 'Bots lendários', 3], ['special', 'Itens especiais', 4]];
for (const [id, name, sort] of cats) p(`insert into public.shop_categories (id, name, sort) values (${q(id)}, ${q(name)}, ${sort}) on conflict (id) do update set name = excluded.name, sort = excluded.sort;`);

// events
p('\n-- events');
for (const ev of Object.values(X.events))
  p(`insert into public.events (id, name, description, color, starts_at, ends_at) values (${q(ev.id)}, ${q(ev.name)}, ${q(ev.desc)}, ${q(ev.color)}, ${q(ev.from + ' 00:00:00-03')}, ${q(ev.until + ' 23:59:59-03')}) on conflict (id) do update set name = excluded.name, description = excluded.description, color = excluded.color, starts_at = excluded.starts_at, ends_at = excluded.ends_at;`);

// items + skins + event items + legendary templates
p('\n-- items (shop, events, Founder, Developer, Beta, Special, legendary bots)');
const SKIN_TARGET = { rack: 'rack', server: 'server', switch: 'switch', storage: 'storage', rackacc: 'rackacc', led: 'led', shirt: 'character', pants: 'character', hair: 'character', hat: 'character', shades: 'character', scarf: 'character', backpack: 'character', chain: 'character' };
for (const it of X.cosmetics) {
  const grant = it.grant || (it.event ? 'event' : 'shop');
  const purchasable = !it.grantOnly && !it.gift && it.price > 0;
  const sellable = it.sell !== false && !it.event && !it.gift && grant === 'shop';
  const slot = it.slot === undefined ? null : it.slot;
  p(`insert into public.items (id, category_id, slot, value, name, description, rarity_id, currency_id, price, stackable, max_quantity, sellable, purchasable, gift, grant_type, event_id, color) values (` +
    [q(it.id), q(it.cat), q(slot), j(it.value === undefined ? null : it.value), q(it.name), q(it.desc), q(it.rarity), q('gold'), it.price || 0, !!it.stack, q(it.max || null), sellable, purchasable, !!it.gift, q(grant), q(it.event || null), q(it.color || null)].join(', ') +
    `) on conflict (id) do update set category_id = excluded.category_id, slot = excluded.slot, value = excluded.value, name = excluded.name, description = excluded.description, rarity_id = excluded.rarity_id, price = excluded.price, stackable = excluded.stackable, max_quantity = excluded.max_quantity, sellable = excluded.sellable, purchasable = excluded.purchasable, gift = excluded.gift, grant_type = excluded.grant_type, event_id = excluded.event_id, color = excluded.color;`);
  if (SKIN_TARGET[slot]) p(`insert into public.skins (item_id, target, theme) values (${q(it.id)}, ${q(SKIN_TARGET[slot])}, ${q(it.theme || null)}) on conflict (item_id) do update set target = excluded.target, theme = excluded.theme;`);
  if (it.event) p(`insert into public.event_items (event_id, item_id, kind) values (${q(it.event)}, ${q(it.id)}, ${q(it.gift ? 'gift' : 'shop')}) on conflict (event_id, item_id) do update set kind = excluded.kind;`);
  if (it.bot) p(`insert into public.legendary_bot_templates (item_id, name, role, level, profile) values (${q(it.id)}, ${q(it.bot.name)}, ${q(it.bot.role)}, 8, ${j(it.bot)}) on conflict (item_id) do update set name = excluded.name, role = excluded.role, profile = excluded.profile;`);
}

// hardware models (server types) and the build catalog prices
p('\n-- server types (hardware models)');
let maxPerf = 1, maxUsable = 1;
for (const kind of ['server', 'switch', 'patch', 'storage']) {
  for (const [id, m] of Object.entries(X.hw[kind] || {})) {
    if (m.perf) maxPerf = Math.max(maxPerf, m.perf);
    if (m.usable) maxUsable = Math.max(maxUsable, m.usable);
    p(`insert into public.server_types (id, kind, name, price, perf, specs) values (${q(id)}, ${q(kind)}, ${q(m.name)}, ${m.price || 0}, ${m.perf || 'null'}, ${j(m)}) on conflict (id) do update set kind = excluded.kind, name = excluded.name, price = excluded.price, perf = excluded.perf, specs = excluded.specs;`);
  }
}
p('\n-- build catalog prices (company $)');
for (const d of X.cat) {
  const unitKind = d.mount === 'rack' ? d.unit || d.id : null;
  p(`insert into public.equipment_prices (id, kind, unit_kind, category, name, price) values (${q(d.id)}, ${q(d.kind)}, ${q(unitKind)}, ${q(d.cat)}, ${q(d.name)}, ${d.price || 0}) on conflict (id) do update set kind = excluded.kind, unit_kind = excluded.unit_kind, category = excluded.category, name = excluded.name, price = excluded.price;`);
}

// achievements
p('\n-- achievements');
for (const [id, name, desc, reward] of [
  ['first_online', 'Primeiro servidor no ar', 'Configure um servidor até ele ficar online.', {}],
  ['first_datacenter', 'Datacenter concluído', 'Conclua o checklist de um datacenter.', { gold: 20 }],
  ['land_owner', 'Terreno próprio', 'Expanda o terreno pela primeira vez.', {}],
  ['legend_owner', 'Lenda na equipe', 'Tenha um bot lendário.', {}],
]) p(`insert into public.achievements (id, name, description, reward) values (${q(id)}, ${q(name)}, ${q(desc)}, ${j(reward)}) on conflict (id) do update set name = excluded.name, description = excluded.description, reward = excluded.reward;`);

// economy config: the server's copy of the client's numbers + anti-cheat caps
const E = X.econ, presets = {};
// (a game from scratch starts with the entrance's plant and water cooler — DL.newWorld)
for (const [id, pr] of Object.entries(X.presets)) presets[id] = { name: pr.name, lot: pr.lot, items: id === 'zero' ? { plant: 1, water: 1 } : pr.items, crew: pr.crew, cash: id === 'zero' ? E.startCash : E.presetCash[id], live: id !== 'zero' };
const reward = 1.35; // the best learning-mode multiplier
const economy = {
  start_cash: E.startCash, presets, starter_kit: E.kit, lot: E.lot,
  salary: E.salary, salary_custom: E.salaryCustom, salary_per_level: E.salaryPerLevel, hire_fee: E.hireFee, month_minutes: E.monthMinutes, opex_floor: E.opexFloor,
  // per game minute, generous on purpose (best hardware, best specialisation, VMs, best mode) — honest play never hits them
  max_rev_per_server: Math.ceil(E.revenuePerServer * maxPerf * 1.6 * reward * 4),
  max_rev_per_storage: Math.ceil(maxUsable * E.storagePerTB * reward * 2),
  max_rev_per_ap: Math.ceil(E.wifiPerAp * reward * 2),
  max_sales_per_min: 600,
  first_contract: Math.ceil(E.firstContract * reward),
  grace_minutes: 180, min_cash: -500000,
  credits_per_min: 4, credits_per_online_min: 0.06, credits_per_server_online: Math.ceil(E.credits.serverSetup * reward), credits_per_incident: Math.ceil((E.credits.incident + E.credits.incidentFast) * reward),
  credits_dc: Math.ceil(E.credits.datacenter * reward), gold_dc: E.gold.datacenter, dc_min_minutes: 60, dc_rewards_per_day: 3, gold_rate: E.gold.rate, welcome_gold: E.gold.welcome,
};
p('\n-- economy config');
p(`insert into public.game_config (key, value) values ('economy', ${j(economy)}) on conflict (key) do update set value = excluded.value, updated_at = now();`);
p(`insert into public.game_config (key, value) values ('server_specializations', ${j(X.svc)}) on conflict (key) do update set value = excluded.value, updated_at = now();`);
p('\ncommit;');
console.log(out.join('\n'));
